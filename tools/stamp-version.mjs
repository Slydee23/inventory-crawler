// Cache busting for GitHub Pages (which lets browsers cache files for 10 minutes).
// Computes a content hash over all site files and writes it into index.html:
//   - an import map that maps every ES module to "<file>?v=<hash>"
//   - ?v=<hash> on the entry script and stylesheet
//   - <meta name="app-version"> (used for fetching data/*.json)
// Run before every commit that changes the site:  node tools/stamp-version.mjs
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const walk = (dir) => readdirSync(dir).flatMap((n) => {
  const p = join(dir, n);
  return statSync(p).isDirectory() ? walk(p) : [p];
});
const rel = (p) => relative(root, p).split('\\').join('/');

const jsFiles = walk(join(root, 'js')).filter((p) => p.endsWith('.js')).map(rel).sort();

/** Content hash over all site assets (js, css, data). */
export function computeVersion() {
  const assets = [...jsFiles, ...walk(join(root, 'css')).map(rel), ...walk(join(root, 'data')).map(rel)].sort();
  const hash = createHash('sha1');
  for (const f of assets) hash.update(f).update(readFileSync(join(root, f)));
  return hash.digest('hex').slice(0, 10);
}

/** Version currently stamped into index.html. */
export function stampedVersion() {
  return /<meta name="app-version" content="([^"]*)">/.exec(readFileSync(join(root, 'index.html'), 'utf8'))?.[1] ?? null;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) stamp();

function stamp() {
const v = computeVersion();

const importMap = JSON.stringify({ imports: Object.fromEntries(jsFiles.map((f) => [`./${f}`, `./${f}?v=${v}`])) }, null, 2)
  .split('\n').map((l) => '  ' + l).join('\n');

const file = join(root, 'index.html');
let html = readFileSync(file, 'utf8');
const block = `<!-- version:start (generated by tools/stamp-version.mjs) -->
  <meta name="app-version" content="${v}">
  <script type="importmap">
${importMap}
  </script>
  <!-- version:end -->`;
if (html.includes('<!-- version:start')) {
  html = html.replace(/<!-- version:start[\s\S]*?<!-- version:end -->/, block);
} else {
  html = html.replace('  <link rel="stylesheet"', `  ${block}\n  <link rel="stylesheet"`);
}
html = html.replace(/href="css\/style\.css(\?v=[^"]*)?"/, `href="css/style.css?v=${v}"`);
html = html.replace(/src="js\/app\.js(\?v=[^"]*)?"/, `src="js/app.js?v=${v}"`);
writeFileSync(file, html);
// other pages only need the versioned stylesheet
for (const page of readdirSync(root).filter((n) => n.endsWith('.html') && n !== 'index.html')) {
  const p = join(root, page);
  writeFileSync(p, readFileSync(p, 'utf8').replace(/href="css\/style\.css(\?v=[^"]*)?"/, `href="css/style.css?v=${v}"`));
}
console.log(`version ${v} (${jsFiles.length} modules)`);
}
